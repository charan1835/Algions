"""
Batch Expiry Risk Classifier & Operational Decision-Support Engine.
Combines mechanistic inventory balance accounting with machine learning risk classification
to flag at-risk batches and provide operational guidance (never clinical advice).
"""

import numpy as np
import pandas as pd
from typing import Dict, Any, List, Tuple
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.preprocessing import StandardScaler
from sklearn.pipeline import Pipeline

ADVISORY_DISCLAIMER = (
    "OPERATIONAL ADVISORY ONLY: Recommendations generated by this system are designed solely "
    "for supply chain, inventory rotation, and replenishment decision support. "
    "They do NOT constitute medical, therapeutic, diagnostic, or clinical prescription advice."
)

class InventoryRiskEngine:
    """
    Evaluates individual batch records using both a physical stock balance rule
    and a supervised classification model.
    """

    def __init__(self, risk_horizon_days: int = 60, random_state: int = 42):
        self.risk_horizon_days = risk_horizon_days
        self.random_state = random_state
        self.classifier = Pipeline([
            ("scaler", StandardScaler()),
            ("model", RandomForestClassifier(n_estimators=100, max_depth=6, random_state=self.random_state, class_weight="balanced"))
        ])
        self.feature_names = [
            "Days_To_Expiry", "Stock_Balance", "Initial_Stock", 
            "Expected_Weekly_Demand", "Stock_Cover_Ratio", 
            "Stock_Cover_Weeks", "Depletion_Percentage"
        ]

    def fit_ml_classifier(self, X: pd.DataFrame, y: pd.Series):
        """Fits the supervised ML classifier on batch-level features."""
        available_features = [col for col in self.feature_names if col in X.columns]
        self.feature_names = available_features
        unique_classes = np.unique(y)
        if len(unique_classes) > 1:
            self.classifier.fit(X[self.feature_names], y)
            self.has_fit = True
        else:
            self.has_fit = False
            self.single_class = int(unique_classes[0]) if len(unique_classes) > 0 else 0
        return self

    def predict_risk_proba(self, X: pd.DataFrame) -> np.ndarray:
        """Returns ML probability of expiry write-off risk."""
        if hasattr(self, "has_fit") and not self.has_fit:
            return np.full(len(X), float(self.single_class))
        
        probs = self.classifier.predict_proba(X[self.feature_names])
        if probs.shape[1] == 1:
            cls = 0
            if hasattr(self.classifier, "named_steps"):
                cls = self.classifier.named_steps["model"].classes_[0]
            elif hasattr(self.classifier, "classes_"):
                cls = self.classifier.classes_[0]
            return np.full(len(X), 1.0 if cls == 1 else 0.0)
        return probs[:, 1]

    def evaluate_batch(self, batch_data: Dict[str, Any], forecasted_weekly_demand: float) -> Dict[str, Any]:
        """
        Assesses a single batch and returns full operational triage information.
        """
        stock = float(batch_data.get("Stock_Balance", 0))
        days_to_exp = float(batch_data.get("Days_To_Expiry", 0))
        weeks_to_exp = max(0.0, days_to_exp / 7.0)
        unit_price = float(batch_data.get("Unit_Price", 10.0))

        # 1. Mechanistic stock balance calculation
        projected_demand = max(0.0, forecasted_weekly_demand * weeks_to_exp)
        projected_excess_units = max(0.0, stock - projected_demand)
        stock_cover_ratio = stock / (projected_demand + 1e-5)
        financial_risk_exposure = projected_excess_units * unit_price

        # 2. Risk Tier assignment
        if days_to_exp <= 0 and stock > 0:
            tier = "EXPIRED"
            action = "QUARANTINE IMMEDIATELY: Do not dispense. Arrange authorized biomedical destruction."
            priority = 1
        elif days_to_exp <= 30 and projected_excess_units > 0:
            tier = "CRITICAL"
            action = "HIGH PRIORITY: Inter-facility transfer to high-volume clinic or emergency clearance discount."
            priority = 2
        elif days_to_exp <= self.risk_horizon_days and projected_excess_units > 0:
            tier = "WARNING"
            action = "STOCK ROTATION: Enforce strict First-Expiry-First-Out (FEFO) dispensing; pause reorders."
            priority = 3
        elif stock_cover_ratio > 3.0:
            tier = "SURPLUS_MONITOR"
            action = "MONITOR: High stock cover relative to velocity. Defer upcoming purchase orders."
            priority = 4
        else:
            tier = "HEALTHY"
            action = "ROUTINE: Stock is well-aligned with demand forecast. Standard inventory cycle."
            priority = 5

        # Feature vector for ML check
        init_stock = float(batch_data.get("Initial_Stock", stock))
        feat_df = pd.DataFrame([{
            "Days_To_Expiry": days_to_exp,
            "Stock_Balance": stock,
            "Initial_Stock": init_stock,
            "Expected_Weekly_Demand": forecasted_weekly_demand,
            "Stock_Cover_Ratio": stock_cover_ratio,
            "Stock_Cover_Weeks": stock / (forecasted_weekly_demand + 1e-5),
            "Depletion_Percentage": max(0.0, min(1.0, (init_stock - stock) / (init_stock + 1e-5)))
        }])

        ml_prob = None
        try:
            if hasattr(self.classifier, "named_steps"):
                ml_prob = float(self.predict_risk_proba(feat_df)[0])
        except Exception:
            ml_prob = 1.0 if tier in ["EXPIRED", "CRITICAL", "WARNING"] else 0.0

        return {
            "batch_id": batch_data.get("Batch_ID", "UNKNOWN"),
            "product_id": batch_data.get("Product_ID", "UNKNOWN"),
            "product_name": batch_data.get("Product_Name", "Unknown Product"),
            "current_stock": stock,
            "days_to_expiry": days_to_exp,
            "forecasted_weekly_demand": round(forecasted_weekly_demand, 1),
            "projected_demand_until_expiry": round(projected_demand, 1),
            "projected_waste_units": round(projected_excess_units, 1),
            "estimated_capital_at_risk": round(financial_risk_exposure, 2),
            "risk_tier": tier,
            "risk_probability": round(ml_prob, 3) if ml_prob is not None else None,
            "recommended_action": action,
            "triage_priority": priority,
            "disclaimer": ADVISORY_DISCLAIMER
        }

    def batch_triage_dataframe(self, df: pd.DataFrame, demand_forecasts: pd.Series) -> pd.DataFrame:
        """Applies risk engine across an entire batch inventory dataframe."""
        results = []
        for idx, row in df.iterrows():
            forecast_val = float(demand_forecasts.iloc[idx]) if idx < len(demand_forecasts) else float(row.get("Units_Sold", 20))
            res = self.evaluate_batch(row.to_dict(), forecast_val)
            results.append(res)
        return pd.DataFrame(results)
